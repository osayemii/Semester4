import tensorflow as tf
import tensorflow_datasets as tfds
import matplotlib.pyplot as plt
import numpy as np

print('Tensorflow version:', tf.__version__)
print('GPU available:', tf.config.list_physical_devices('GPU'))

# Part B: Load the cat and dog dataset
# 0 = Cat
# 1 = Dog

(train_data, val_data), info = tfds.load(
    'cats_vs_dogs',
    split=['train[:80%]', 'train[80%:]'],
    as_supervised=True,
    with_info=True
)

IMG_SIZE = 128
BATCH_SIZE = 32

# Resize and normalize
def preprocess(image, label):
  image = tf.image.resize(image, (IMG_SIZE, IMG_SIZE))
  image = tf.cast(image, tf.float32) / 255.0
  return image, label

# Prepare training data
train_ds = (
    train_data
    .map(preprocess, num_parallel_calls=tf.data.AUTOTUNE)
    .shuffle(2000)
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)

# Prepare validation data
val_ds = (
    val_data
    .map(preprocess, num_parallel_calls=tf.data.AUTOTUNE)
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)

print('Dataset loaded successfully!')

# Display sample images before training

class_names = ['Cat', 'Dog']

images, labels = next(iter(train_ds))

plt.figure(figsize=(12, 6))

for i in range(8):
    plt.subplot(2, 4, i + 1)

    plt.imshow(images[i].numpy())

    plt.title(class_names[int(labels[i].numpy())])

    plt.axis('off')

plt.suptitle('Training Dataset: Cats and Dogs')
plt.tight_layout()
plt.show()

# Building the CNN Architechture
from tensorflow.keras import Sequential
from tensorflow.keras.layers import (
    Input,
    Conv2D,
    MaxPooling2D,
    Flatten,
    Dense,
    Dropout
)

model = Sequential([

    Input(shape=(128, 128, 3)),

    # First convolutinal section
    Conv2D(32, (3, 3), activation='relu', name='conv1'),
    MaxPooling2D((2, 2), name='pool1'),

    # Second convolutional section
    Conv2D(64, (3, 3), activation='relu', name='conv2'),
    MaxPooling2D((2, 2), name='pool2'),

    # Third convolutional section
    Conv2D(128, (3, 3), activation='relu', name='conv3'),
    MaxPooling2D((2, 2), name='pool3'),

    # Classification section
    Flatten(),

    Dense(128, activation='relu'),

    Dropout(0.5),

    Dense(2, activation='softmax')
])

model.summary()

# Compile and train the CNN
model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

history = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=5
)

# Display training performance
plt.figure(figsize=(12, 5))

# Accuracy graph
plt.subplot(1, 2, 1)
plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.title('CNN Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend()

# Loss graph
plt.subplot(1, 2, 2)
plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title('CNN Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()

# Select a Cat Image
sample_image = None

for image, label in val_data.map(preprocess):
    if int(label.numpy()) == 0:
        sample_image = image
        break

if sample_image is None:
    raise ValueError('No cat image found.')

plt.figure(figsize=(5, 5))
plt.imshow(sample_image.numpy())
plt.title('Original Input Image - CAT')
plt.axis('off')
plt.show()

# Extract outputs from each convolutional layer

# Ensure the model has been called
_ = model(tf.zeros((1, 128, 128, 3)))

# Extract convolutional layer outputs
layer_outputs = [
    model.get_layer('conv1').output,
    model.get_layer('conv2').output,
    model.get_layer('conv3').output
]

# Create visualization model
activation_model = tf.keras.Model(
    inputs=model.inputs,
    outputs=layer_outputs
)

# Pass the cat image thorugh a network
activations = activation_model.predict(
    np.expand_dims(sample_image.numpy(), axis=0)
)

print('Convolutional layers visualized successfully!')

# Display the feature maps

def display_feature_maps(activations_list, layer_name):

    num_features = min(4, activations_list.shape[-1])
    plt.figure(figsize=(15, 3))

    for i in range(num_features):
        plt.subplot(1, 4, i + 1)
        plt.imshow(activations_list[0, :, :, i], cmap='viridis')
        plt.title(f'Feature Map {i + 1}')
        plt.axis('off')

    plt.suptitle(
        f'{layer_name}: Learned Feature Maps',
        fontsize=16
    )
    plt.tight_layout()
    plt.show()

# First convolutional layer
display_feature_maps(activations[0], 'CONVOLUTIONAL LAYER 1')

# Second convolutional layer
display_feature_maps(activations[1], 'CONVOLUTIONAL LAYER 2')

# Third convolutional layer
display_feature_maps(activations[2], 'CONVOLUTIONAL LAYER 3')

# visualize the actual learned filters

# Get weights from the first convolutional layer
filters, biases = model.get_layer('conv1').get_weights()

plt.figure(figsize=(12, 8))

for i in range(16):
    kernel = filters[:, :, :, i]

    # Normalize for visualization
    kernel = (kernel - kernel.min()) / (kernel.max() - kernel.min() + 1e-8)

    plt.subplot(4, 4, i + 1)
    plt.imshow(kernel)
    plt.axis('off')
    plt.title(f'Filter {i+1}')

plt.suptitle('Learned Filters - First Convolutional Layer')
plt.tight_layout()
plt.show()

# Make the final prediction

prediction = model.predict(np.expand_dims(sample_image.numpy(), axis=0))

# Get predicted class
predicted_class = np.argmax(prediction[0])

confidence = prediction[0][predicted_class] * 100

# Display final result
plt.figure(figsize=(7, 7))
plt.imshow(sample_image.numpy())
plt.title(
    f'FINAL PREDICTION: {class_names[predicted_class]}\nConfidence: {confidence:.2f}%',
    fontsize=16
)

plt.axis('off')
plt.show()

# Print probabilities
print('=============================== CNN FINAL RESULTS ===============================')

print(f'Cat probability: {prediction[0][0] * 100:.2f}%')

print(f'Dog probability: {prediction[0][1] * 100:.2f}%')

print('---------------------------------------------------------------------------------')

print('Predicted class:', class_names[predicted_class])

print('Confidence:', f'{confidence:.2f}%')

print('---------------------------------------------------------------------------------')

# Print analysis
# Display training and validation accuracy

print('Training accuracy:', history.history['accuracy'][-1])

print('Validation accuracy:', history.history['val_accuracy'][-1])

print('Training loss:', history.history['loss'][-1])

print('Validation loss:', history.history['val_loss'][-1])

